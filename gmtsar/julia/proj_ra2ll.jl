include(joinpath(@__DIR__, "gmtsar_common.jl"))   # script-to-script calls

"""awk's automatic string-to-number coercion: parse the leading numeric prefix of a string,
   ignoring any trailing non-numeric text; 0.0 if there is none"""
function awk_num(s::AbstractString)
    m = match(r"^[+-]?[0-9]*\.?[0-9]+([eE][+-]?[0-9]+)?", s)
    return m === nothing ? 0.0 : parse(Float64, m.match)
end

function main(argv::Vector{String})
    local V::Vector{String}
    if isfile(joinpath(homedir(), ".quiet"))
        V = String[]
    else
        V = ["-V"]
    end

    #
    #
    #  project a grd file from range/azimuth coordinates into lon/lat coordinates
    #  this version only works with GMT V4.0 and higher
    #
    #  Input:
    #  trans.dat    - file generated by llt_grid2rat  (r a topo lon lat)
    #  phase_ra.grd - a GRD file of phase or anything
    #
    #  Output:
    #  phase_ll.grd - a GRD file of phase in longitude/latitude coordinates
    #
    # check for number of arguments
    #
    if length(argv) != 3 && length(argv) != 4
        println(" ")
        println("Usage: proj_ra2ll.csh trans.dat phase.grd phase_ll.grd [filter_wavelength]")
        println("        trans.dat    - file generated by llt_grid2rat  (r a topo lon lat)")
        println("        phase_ra.grd - a GRD file of phase or anything")
        println("        phase_ll.grd - output file in lon/lat-coordinates")
        println("        filter_wavelength - will sample every 1/4 wavelength (in meters) ")
        println(" ")
        exit(1)
    end
    println("proj_ra2ll.csh")
    #
    #  extract the phase in the r a positions
    #
    run(pipeline(`gmt grd2xyz $(argv[2]) -s -bo3f`, stdout="rap"))
    #
    #   make grids of longitude and latitude versus range and azimuth unless they already exist
    #
    if !isfile("raln.grd") || !isfile("ralt.grd")
        region = strip(read(`gmt gmtinfo rap -I16/32 -bi3f`, String))
        run(`gmt surface $(argv[1]) -i0,1,3 -bi5d $region -I16/32 -T.50 -Graln.grd $V`)
        run(`gmt surface $(argv[1]) -i0,1,4 -bi5d $region -I16/32 -T.50 -Gralt.grd $V`)
    end
    #
    #  add lon and lat columns and then just keep lon, lat, phase
    #
    run(pipeline(pipeline(`gmt grdtrack rap -nl -bi3f -bo5f -Graln.grd -Gralt.grd`, `gmt gmtconvert -bi5f -bo3f -o3,4,2`), stdout="llp"))
    #
    # set the output grid spaccing to be 1/4 the filter wavelength
    #
    local pix_m::String
    if length(argv) == 4
        filt_wave = argv[4]
        pix_m = string(parse(Float64, filt_wave) / 4)
        println("Sampling in geocoordinates with $pix_m meter pixels ...")
    else
        gauss_files = sort(filter(f -> startswith(f, "gauss_"), readdir(".")))
        if !isempty(gauss_files)
            vals = String[]
            for f in gauss_files
                parts = split(f, "_")
                v = length(parts) >= 2 ? awk_num(parts[2]) / 4 : 0.0 / 4  # Use 1/4 the filter width
                push!(vals, string(v))
            end
            pix_m = join(vals, " ")
            println("Sampling in geocoordinates with $pix_m meter pixels ...")
        else
            pix_m = "60"
            println("Sampling in geocoordinates with deault ($pix_m meter) pixel size ...")
        end
    end

    incs = split(strip(read(`$GMTSAR_JULIA $(gmtsar_script("m2s")) $pix_m llp`, String)))			  # Get fine and crude grid interval for lookup grids
    #
    R = strip(read(`gmt gmtinfo llp -I$(incs[2]) -bi3f`, String))
    run(pipeline(`gmt blockmedian llp $R -bi3f -bo3f -I$(incs[1]) -r -V`, stdout="llpb"))
    run(`gmt xyz2grd llpb $R -I$(incs[1]) -r -fg -G$(argv[3]) -bi3f`)
    #
    # clean
    #
    for f in readdir(".")
        if startswith(f, "rap")
            rm(f; force=true)
        end
    end
    rm("llp"; force=true)
    rm("llpb"; force=true)
    rm("raln"; force=true)
    rm("ralt"; force=true)
end

main(filter(!isempty, ARGS))   # csh drops empty (unset) arguments
